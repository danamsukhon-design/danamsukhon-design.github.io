<#
  prepare-images.ps1  -  run after adding or replacing artwork.

  For every JPG/PNG in assets/images/<folder>/ it:
    1. writes a web-sized copy to assets/images/<folder>/thumbs/ (600 px wide, used in grids)
    2. records the image's width and height in assets/images/manifest.js
       (the site uses these to reserve space, so nothing jumps while images load)

  Usage (from the website folder):
      powershell -ExecutionPolicy Bypass -File tools\prepare-images.ps1
  Options:
      -ThumbWidth 600   width of the grid copies
      -Quality 82       JPEG quality of the grid copies
      -Force            rebuild thumbs that already exist
#>
param([int]$ThumbWidth = 600, [int]$Quality = 82, [switch]$Force)

Add-Type -AssemblyName System.Drawing
$root   = Split-Path -Parent $PSScriptRoot
$images = Join-Path $root 'assets\images'
$codec  = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object { $_.MimeType -eq 'image/jpeg' }
$params = New-Object System.Drawing.Imaging.EncoderParameters 1
$params.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality, [long]$Quality)

$entries = New-Object System.Collections.Generic.List[string]
$made = 0
Get-ChildItem $images -Directory | Sort-Object Name | ForEach-Object {
  $dir = $_
  $thumbDir = Join-Path $dir.FullName 'thumbs'
  Get-ChildItem $dir.FullName -File | Where-Object { $_.Extension -match '^\.(jpe?g|png)$' } | Sort-Object Name | ForEach-Object {
    $file = $_
    $img = [System.Drawing.Image]::FromFile($file.FullName)
    $w = $img.Width; $h = $img.Height
    $entries.Add(('  "{0}/{1}": [{2}, {3}]' -f $dir.Name, $file.Name, $w, $h))

    $out = Join-Path $thumbDir ([IO.Path]::GetFileNameWithoutExtension($file.Name) + '.jpg')
    if ($Force -or -not (Test-Path $out)) {
      if (-not (Test-Path $thumbDir)) { New-Item -ItemType Directory $thumbDir | Out-Null }
      $tw = [Math]::Min($ThumbWidth, $w); $th = [int][Math]::Round($h * $tw / $w)
      $bmp = New-Object System.Drawing.Bitmap $tw, $th
      $g = [System.Drawing.Graphics]::FromImage($bmp)
      $g.InterpolationMode  = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
      $g.PixelOffsetMode    = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
      $g.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
      $g.SmoothingMode      = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
      $attr = New-Object System.Drawing.Imaging.ImageAttributes
      $attr.SetWrapMode([System.Drawing.Drawing2D.WrapMode]::TileFlipXY)
      $g.Clear([System.Drawing.Color]::White)
      $g.DrawImage($img, (New-Object System.Drawing.Rectangle 0, 0, $tw, $th), 0, 0, $w, $h, [System.Drawing.GraphicsUnit]::Pixel, $attr)
      $bmp.Save($out, $codec, $params)
      $g.Dispose(); $bmp.Dispose(); $attr.Dispose()
      $made++
    }
    $img.Dispose()
  }
}

$js = "// Generated by tools/prepare-images.ps1 - do not edit by hand.`n// width and height of every image, keyed by folder/file.`nwindow.IMG_DIMS = {`n" + ($entries -join ",`n") + "`n};`n"
[IO.File]::WriteAllText((Join-Path $images 'manifest.js'), $js, (New-Object System.Text.UTF8Encoding $false))
"{0} images listed, {1} thumbs written." -f $entries.Count, $made
